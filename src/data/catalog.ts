/** 냉동실에 둔 재료는 두 달로 본다 */
const FREEZER_DAYS = 60

/** 목록에 없는 재료(직접 입력)는 둔 칸으로 짐작한다 */
const PLACE_FALLBACK_DAYS: Partial<Record<Place, number>> = { veg: 7, fruit: 7, main: 7, door: 7 }

/** 이 재료를 산 날부터 며칠 보는지. null = 오래가서 세지 않음 */
export function shelfDaysFor(name: string, place: Place): number | null {
  if (place === 'freezer') return FREEZER_DAYS
  if (name in SHELF_DAYS) return SHELF_DAYS[name]
  if (findCatalog(name)) return null
  return PLACE_FALLBACK_DAYS[place] ?? null
}

export function findCatalog(name: string): CatalogItem | undefined {
  return CATALOG.find((item) => item.name === name)
}
